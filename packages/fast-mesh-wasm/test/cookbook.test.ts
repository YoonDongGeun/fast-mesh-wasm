// Cookbook snippet tests: every runnable ```ts block in docs/cookbook/*.md
// runs against the built package (dist/), exactly like a user install.
//
// Mechanism: extract-and-run. For each recipe file the harness concatenates
// its ```ts fences in order into one module and imports it; a recipe passes
// when its module runs to completion. Recipes raise on unexpected values
// with plain `throw`, so no test framework leaks into the docs. Fences
// tagged ```ts no-run need reader-supplied data (a .drc file's bytes) and
// are skipped; the skipped set is asserted below, so a new skip fails until
// it is acknowledged here. README.md is the index, not a recipe (its fence
// shows alternative imports), and is not run.
//
// The headless-node recipe's `./worker.js` is the engine script the reader
// writes; the harness materializes an equivalent file (this repo's own
// worker_threads engine harness) next to the generated module so the
// snippet's relative URL resolves.
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { describe, expect, it } from "vitest";

const here = dirname(fileURLToPath(import.meta.url));
const cookbookDir = join(here, "..", "..", "..", "docs", "cookbook");
const outDir = join(here, "__cookbook__");

/** Skipped fences as `${file} block ${1-based fence index}`: each needs an entry here. */
const SKIPPED = new Set([
  // decodeDraco runs on the reader's own .drc bytes; there is nothing to run it on here.
  "io-export-import.md block 4",
]);

/** The recipes issue #122 requires (kept filenames on main; see the report). */
const REQUIRED = [
  "load-repair-color-export.md",
  "contact-heatmap.md",
  "headless-node.md",
  "custom-colormap.md",
];

interface Recipe {
  file: string;
  url: string;
  /** Generated-module line where each runnable block's marker sits. */
  blocks: { fence: number; start: number }[];
}

interface Extracted extends Recipe {
  source: string;
  skipped: string[];
}

/** Concatenates a recipe's runnable fences into one module (not yet written). */
function extract(file: string): Extracted {
  const lines = readFileSync(join(cookbookDir, file), "utf8").split(/\r?\n/);
  const out: string[] = [`// Generated by test/cookbook.test.ts from docs/cookbook/${file}: do not edit.`];
  const blocks: Extracted["blocks"] = [];
  const skipped: string[] = [];
  let fence = 0;
  let body: string[] | null = null;
  let tags: string[] = [];
  let first = 0;
  for (const [index, line] of lines.entries()) {
    if (!line.trimStart().startsWith("```")) {
      body?.push(line);
      continue;
    }
    if (body === null) {
      const tokens = line.trimStart().slice(3).split(/\s+/).filter((t) => t.length > 0);
      if (tokens[0] === "ts") {
        fence += 1;
        body = [];
        tags = tokens.slice(1);
        first = index + 2; // the fence's first body line, 1-based
      }
      continue;
    }
    const last = index; // the fence's last body line, 1-based
    const id = `${file} block ${fence}`;
    if (tags.includes("no-run")) {
      skipped.push(id);
    } else {
      blocks.push({ fence, start: out.length + 1 });
      out.push(`// ---- ${id} (md lines ${first}-${last}) ----`, ...body);
    }
    body = null;
  }
  return { file, url: "", blocks, source: out.join("\n"), skipped };
}

/** Names the recipe block a stack trace's generated-module line falls in. */
function attribute(recipe: Recipe, error: unknown): unknown {
  const stack = error instanceof Error ? (error.stack ?? "") : "";
  const match = /__cookbook__[^:]*:(\d+):\d+/.exec(stack);
  const line = match === null ? -1 : Number(match[1]);
  let fence = -1;
  for (const block of recipe.blocks) {
    if (block.start <= line) {
      fence = block.fence;
    }
  }
  if (error instanceof Error && fence !== -1) {
    error.message += ` [docs/cookbook/${recipe.file} block ${fence}]`;
  }
  return error;
}

rmSync(outDir, { recursive: true, force: true });
mkdirSync(outDir, { recursive: true });
// The headless-node recipe's engine script, standing in for the reader's own.
writeFileSync(join(outDir, "worker.js"), 'import "../harness/node-worker.mjs";\n');

const files = readdirSync(cookbookDir)
  .filter((name) => name.endsWith(".md") && name !== "README.md")
  .sort();
const recipes: Recipe[] = [];
const skipped: string[] = [];
for (const file of files) {
  const recipe = extract(file);
  const stem = file.slice(0, -".md".length);
  writeFileSync(join(outDir, `${stem}.ts`), `${recipe.source}\n`);
  recipes.push({ ...recipe, url: pathToFileURL(join(outDir, `${stem}.ts`)).href });
  skipped.push(...recipe.skipped);
}

describe("cookbook", () => {
  it("covers the recipes issue #122 requires", () => {
    for (const file of REQUIRED) {
      expect(files).toContain(file);
    }
  });

  it("gives every recipe at least one runnable fence", () => {
    expect(recipes.length).toBeGreaterThan(0);
    for (const recipe of recipes) {
      expect(recipe.blocks.length, recipe.file).toBeGreaterThan(0);
    }
  });

  it("skips exactly the documented fences", () => {
    expect(skipped.sort()).toEqual([...SKIPPED].sort());
  });

  for (const recipe of recipes) {
    it(`${recipe.file} runs against the built package`, async () => {
      try {
        await import(recipe.url);
      } catch (error: unknown) {
        throw attribute(recipe, error);
      }
    });
  }
});
